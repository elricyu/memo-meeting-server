CREATE TABLE IF NOT EXISTS speakers (
 meeting_id VARCHAR(36) NOT NULL REFERENCES meetings(id), speaker_id VARCHAR(100) NOT NULL,
 name VARCHAR(60) NOT NULL, PRIMARY KEY(meeting_id,speaker_id)
);
CREATE TABLE IF NOT EXISTS web_bindings (
 id VARCHAR(36) PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),code VARCHAR(8) NOT NULL UNIQUE,
 expires_at BIGINT NOT NULL,status VARCHAR(16) NOT NULL,device_id VARCHAR(36) REFERENCES devices(id),pairing_id VARCHAR(36) REFERENCES pairings(id)
);
CREATE INDEX IF NOT EXISTS idx_web_binding_owner ON web_bindings(user_id,status);

