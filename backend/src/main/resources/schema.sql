CREATE TABLE IF NOT EXISTS meetings (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(200) NOT NULL, context VARCHAR(400) NOT NULL,
 recorder_hash VARCHAR(64) NOT NULL, status VARCHAR(24) NOT NULL,
 created_at VARCHAR(40) NOT NULL, updated_at VARCHAR(40) NOT NULL,
 audio_bytes BIGINT NOT NULL DEFAULT 0, error VARCHAR(600) NOT NULL DEFAULT '',
 summary CLOB NOT NULL DEFAULT '', summary_status VARCHAR(24) NOT NULL DEFAULT 'IDLE',
 summary_error VARCHAR(600) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS segments (
 meeting_id VARCHAR(36) NOT NULL REFERENCES meetings(id), segment_id VARCHAR(100) NOT NULL,
 start_ms BIGINT NOT NULL, end_ms BIGINT NOT NULL, content CLOB NOT NULL,
 PRIMARY KEY(meeting_id, segment_id)
);
CREATE INDEX IF NOT EXISTS idx_segments_time ON segments(meeting_id, start_ms);

ALTER TABLE meetings ADD COLUMN IF NOT EXISTS original_title VARCHAR(200);
UPDATE meetings SET original_title=title WHERE original_title IS NULL;

ALTER TABLE meetings ADD COLUMN IF NOT EXISTS source VARCHAR(16) NOT NULL DEFAULT 'WEB';
ALTER TABLE meetings ADD COLUMN IF NOT EXISTS client_request_id VARCHAR(36);
CREATE UNIQUE INDEX IF NOT EXISTS idx_meeting_request ON meetings(client_request_id);

CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE, display_name VARCHAR(60) NOT NULL,
 password_hash VARCHAR(100) NOT NULL, created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS devices (
 id VARCHAR(36) PRIMARY KEY, hardware_id VARCHAR(128) NOT NULL,
 display_name VARCHAR(64) NOT NULL, platform VARCHAR(32) NOT NULL,
 owner_id BIGINT REFERENCES users(id), token_hash VARCHAR(64) NOT NULL UNIQUE,
 status VARCHAR(16) NOT NULL, request_id VARCHAR(36) NOT NULL UNIQUE,
 created_at VARCHAR(40) NOT NULL, updated_at VARCHAR(40) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_device_owner ON devices(owner_id,status);
CREATE TABLE IF NOT EXISTS pairings (
 id VARCHAR(36) PRIMARY KEY, device_id VARCHAR(36) NOT NULL REFERENCES devices(id),
 code VARCHAR(8) NOT NULL UNIQUE, expires_at BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL
);
ALTER TABLE meetings ADD COLUMN IF NOT EXISTS owner_id BIGINT REFERENCES users(id);
ALTER TABLE meetings ADD COLUMN IF NOT EXISTS device_id VARCHAR(36) REFERENCES devices(id);
CREATE INDEX IF NOT EXISTS idx_meeting_owner ON meetings(owner_id,created_at);

ALTER TABLE devices ADD COLUMN IF NOT EXISTS client_id VARCHAR(128);
ALTER TABLE devices ADD COLUMN IF NOT EXISTS mac VARCHAR(17) NOT NULL DEFAULT '';
UPDATE devices SET client_id=hardware_id WHERE client_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_device_client ON devices(client_id,status);
CREATE INDEX IF NOT EXISTS idx_device_mac ON devices(mac,status);

ALTER TABLE devices ADD COLUMN IF NOT EXISTS active_client VARCHAR(128) GENERATED ALWAYS AS (CASE WHEN status IN ('PENDING','BOUND') THEN client_id ELSE NULL END);
ALTER TABLE devices ADD COLUMN IF NOT EXISTS active_mac VARCHAR(17) GENERATED ALWAYS AS (CASE WHEN status IN ('PENDING','BOUND') THEN mac ELSE NULL END);
CREATE UNIQUE INDEX IF NOT EXISTS idx_device_active_client ON devices(active_client);
CREATE UNIQUE INDEX IF NOT EXISTS idx_device_active_mac ON devices(active_mac);

CREATE TABLE IF NOT EXISTS ai_configs (
 user_id BIGINT NOT NULL REFERENCES users(id), kind VARCHAR(8) NOT NULL,
 provider VARCHAR(40) NOT NULL, model VARCHAR(128) NOT NULL,
 vocabulary_id VARCHAR(128) NOT NULL DEFAULT '', language VARCHAR(16) NOT NULL DEFAULT 'zh',
 diarization BOOLEAN NOT NULL DEFAULT FALSE, reuse_asr_key BOOLEAN NOT NULL DEFAULT FALSE,
 key_cipher VARCHAR(4096) NOT NULL DEFAULT '', updated_at VARCHAR(40) NOT NULL,
 PRIMARY KEY(user_id,kind)
);
